func writeTree(t *testing.T, root string, files map[string]string, mode os.FileMode) {
	t.Helper()
	for p, content := range files {
		full := filepath.Join(root, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(content), mode); err != nil {
			t.Fatal(err)
		}
	}
}

// cronHost speelt een node met cron en een paar timers na.
func cronHost(t *testing.T, now time.Time, journal *string) *Collector {
	t.Helper()
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"/etc/crontab": "SHELL=/bin/sh\nPATH=/usr/local/sbin:/usr/bin\n# m h dom mon dow user\tcommand\n" +
			"17 *\t* * *\troot\tcd / && run-parts --report /etc/cron.hourly\n",
		"/etc/cron.d/galera-bootstrap":  "# oude cron van Jonas\n*/5 * * * * root /usr/local/bin/galera-check.sh >/dev/null 2>&1\n",
		"/etc/cron.d/nextcloud-sync":    "MAILTO=\"\"\n0 */6 * * * root rsync -a --delete /var/www/nextcloud/data/ root@192.168.10.187:/var/www/nextcloud/data/\n",
		"/etc/cron.d/e2scrub_all":       "30 3 * * 0 root test -e /run/systemd/system || SERVICE_MODE=1 /usr/lib/x86_64-linux-gnu/e2fsprogs/e2scrub_all_cron\n",
		"/etc/cron.d/oud.dpkg-old":      "* * * * * root /bin/false\n",
		"/var/spool/cron/crontabs/root": "# DO NOT EDIT THIS FILE\n@reboot /usr/local/bin/start.sh\n15 2 * * * mysqldump -uroot -pGeheim nextcloud | gzip > /backup/nc.sql.gz\n",
		"/proc/812/cmdline":             "/usr/sbin/cron\x00-f\x00-P\x00-L\x0015\x00",
	}, 0o644)
	writeTree(t, root, map[string]string{"/etc/cron.daily/logrotate": "#!/bin/sh\n", "/etc/cron.daily/.placeholder": ""}, 0o755)
	writeTree(t, root, map[string]string{"/etc/cron.daily/niet-uitvoerbaar": "#!/bin/sh\n"}, 0o644)
	last := now.Add(-2 * time.Hour).Unix()
	return &Collector{Root: root, Run: func(_ context.Context, name string, args ...string) ([]byte, error) {
		all := strings.Join(args, " ")
		switch {
		case name == "systemctl" && strings.HasPrefix(all, "list-units"):
			return []byte("apt-daily.timer loaded active waiting Daily apt download activities\nbackup.timer loaded active waiting Back-up\n"), nil
		case name == "systemctl" && strings.HasPrefix(all, "list-unit-files"):
			return []byte("apt-daily.timer enabled enabled\nbackup.timer enabled enabled\nuit.timer disabled enabled\nfoo@.timer static -\n"), nil
		case name == "systemctl" && strings.Contains(all, "cron.service"):
			return []byte("ActiveState=active\nMainPID=812\n"), nil
		case name == "systemctl" && strings.Contains(all, "crond.service"), name == "systemctl" && strings.Contains(all, "cronie.service"):
			return []byte("ActiveState=inactive\nMainPID=0\n"), nil
		case name == "systemctl" && strings.Contains(all, "apt-daily.timer"):
			return []byte(fmt.Sprintf("Id=apt-daily.timer\nDescription=Daily apt download activities\nUnit=apt-daily.service\nUnitFileState=enabled\n"+
				"ActiveState=active\nNextElapseUSecRealtime=@%d\nLastTriggerUSec=@%d\n"+
				"TimersCalendar={ OnCalendar=*-*-* 06,18:00:00 ; next_elapse=Sat 2026-10-18 18:00:00 CEST }\nFragmentPath=/lib/systemd/system/apt-daily.timer\n\n"+
				"Id=backup.timer\nUnit=backup.service\nUnitFileState=enabled\nActiveState=active\nLastTriggerUSec=@%d\n"+
				"TimersMonotonic={ OnUnitActiveUSec=6h ; next_elapse=1h }\nFragmentPath=/etc/systemd/system/backup.timer\n\n"+
				"Id=uit.timer\nUnit=uit.service\nUnitFileState=disabled\nActiveState=inactive\nFragmentPath=/etc/systemd/system/uit.timer\n\n",
				now.Add(4*time.Hour).Unix(), last, last)), nil
		case name == "systemctl" && strings.Contains(all, "apt-daily.service"):
			return []byte(fmt.Sprintf("Id=apt-daily.service\nExecStart={ path=/usr/lib/apt/apt.systemd.daily ; argv[]=/usr/lib/apt/apt.systemd.daily update ; ignore_errors=no ; start_time=[n/a] ; stop_time=[n/a] ; pid=0 ; code=(null) ; status=0/0 }\n"+
				"Result=success\nExecMainStatus=0\nExecMainStartTimestamp=@%d\nExecMainExitTimestamp=@%d\nActiveState=inactive\n\n"+
				"Id=backup.service\nDescription=Back-up naar de NAS\nExecStart={ path=/usr/local/bin/backup ; argv[]=/usr/local/bin/backup --password=hunter2 ; ignore_errors=no }\n"+
				"Result=exit-code\nExecMainStatus=3\nExecMainStartTimestamp=@%d\nExecMainExitTimestamp=@%d\nActiveState=failed\nUser=backup\n\n"+
				"Id=uit.service\nActiveState=inactive\n\n", last, last+30, last, last+5)), nil
		case name == "dpkg-query":
			var out []string
			for _, p := range args[1:] {
				switch p {
				case "/etc/cron.d/e2scrub_all":
					out = append(out, "e2fsprogs: "+p)
				case "/etc/cron.daily/logrotate":
					out = append(out, "logrotate: "+p)
				case "/usr/lib/systemd/system/apt-daily.timer":
					out = append(out, "apt: "+p)
				}
			}
			return []byte(strings.Join(out, "\n") + "\n"), fmt.Errorf("exit status 1")
		case name == "journalctl":
			out := *journal
			*journal = "-- cursor: s=2\n"
			return []byte(out), nil
		}
		return nil, fmt.Errorf("onbekend: %s %s", name, all)
	}}
}

func TestCronList(t *testing.T) {
	now := time.Now().UTC().Truncate(time.Second)
	ts := func(d time.Duration) string { return fmt.Sprintf("%d.000000", now.Add(-d).Unix()) }
	journal := strings.Join([]string{
		ts(3*time.Hour) + " nc1 CRON[900]: (root) CMD (rsync -a --delete /var/www/nextcloud/data/ root@192.168.10.187:/var/www/nextcloud/data/)",
		ts(3*time.Hour-40*time.Second) + " nc1 CRON[900]: (root) END (rsync -a --delete /var/www/nextcloud/data/ root@192.168.10.187:/var/www/nextcloud/data/)",
		ts(10*time.Minute) + " nc1 CRON[901]: (root) CMD ([902] /usr/local/bin/galera-check.sh >/dev/null 2>&1)",
		ts(10*time.Minute-time.Second) + " nc1 CRON[901]: (CRON) error (grandchild #902 failed with exit status 1)",
		ts(10*time.Minute-time.Second) + " nc1 CRON[901]: (root) END ([902] /usr/local/bin/galera-check.sh >/dev/null 2>&1)",
		ts(5*time.Minute) + " nc1 CRON[903]: (root) CMD ([904] /usr/local/bin/galera-check.sh >/dev/null 2>&1)",
		ts(5*time.Minute-time.Second) + " nc1 CRON[903]: (root) END ([904] /usr/local/bin/galera-check.sh >/dev/null 2>&1)",
		ts(time.Minute) + " nc1 CRON[905]: (root) CMD (mysqldump -uroot -pGeheim nextcloud | gzip > /backup/nc.sql.gz)",
		"-- cursor: s=1",
	}, "\n") + "\n"
	a := &Agent{Collector: cronHost(t, now, &journal)}
	res := a.cronList(context.Background())
	if res.Error != "" || res.Daemon != "cron" || !res.Logging || !res.Journal {
		t.Fatalf("antwoord: %+v", res)
	}
	byFile := map[string]protocol.CronEntry{}
	for _, e := range res.Entries {
		byFile[fmt.Sprintf("%s:%d", e.File, e.Line)] = e
	}
	if len(res.Entries) != 10 {
		b, _ := json.MarshalIndent(res.Entries, "", " ")
		t.Fatalf("%d jobs, wil 10:\n%s", len(res.Entries), b)
	}
	sync := byFile["/etc/cron.d/nextcloud-sync:2"]
	if sync.User != "root" || sync.Schedule != "0 */6 * * *" || sync.LastResult != protocol.CronOK || sync.LastExit == nil || *sync.LastExit != 0 || sync.Runs != 1 {
		t.Errorf("sync: %+v", sync)
	}
	galera := byFile["/etc/cron.d/galera-bootstrap:2"]
	if galera.LastResult != protocol.CronOK || galera.Runs != 2 || galera.Failures != 1 || galera.Command != "/usr/local/bin/galera-check.sh >/dev/null 2>&1" {
		t.Errorf("galera: %+v", galera)
	}
	dump := byFile["/var/spool/cron/crontabs/root:3"]
	if dump.Source != protocol.CronSourceUser || dump.User != "root" || dump.LastResult != protocol.CronRunning || strings.Contains(dump.Command, "Geheim") {
		t.Errorf("dump: %+v", dump)
	}
	if e := byFile["/var/spool/cron/crontabs/root:2"]; e.Schedule != "@reboot" || e.Command != "/usr/local/bin/start.sh" {
		t.Errorf("reboot: %+v", e)
	}
	if e := byFile["/etc/cron.d/e2scrub_all:1"]; e.Package != "e2fsprogs" {
		t.Errorf("e2scrub: %+v", e)
	}
	if e := byFile["/etc/cron.daily/logrotate:0"]; e.Source != protocol.CronSourcePeriodic || e.Schedule != "daily" || e.Package != "logrotate" {
		t.Errorf("logrotate: %+v", e)
	}
	apt := byFile["apt-daily.timer:0"]
	if apt.Schedule != "OnCalendar=*-*-* 06,18:00:00" || apt.Command != "/usr/lib/apt/apt.systemd.daily update" || apt.LastResult != protocol.CronOK ||
		apt.NextRun == nil || apt.Package != "apt" || !apt.Enabled || apt.LastEnd == nil {
		t.Errorf("apt-daily: %+v", apt)
	}
	backup := byFile["backup.timer:0"]
	if backup.Schedule != "OnUnitActiveSec=6h" || backup.LastResult != protocol.CronFailed || backup.LastExit == nil || *backup.LastExit != 3 ||
		backup.User != "backup" || backup.Command != "/usr/local/bin/backup --password=***" || backup.Description != "Back-up naar de NAS" {
		t.Errorf("backup: %+v", backup)
	}
	if e := byFile["uit.timer:0"]; e.Enabled || e.LastRun != nil {
		t.Errorf("uit: %+v", e)
	}

	// De tweede keer leest de agent alleen wat nieuw is, en onthoudt hij de
	// runs van de eerste keer.
	res = a.cronList(context.Background())
	for _, e := range res.Entries {
		if e.File == "/etc/cron.d/galera-bootstrap" && e.Runs != 2 {
			t.Errorf("tweede keer: %+v", e)
		}
	}
	if a.cron.cursor != "s=2" {
		t.Errorf("cursor %q", a.cron.cursor)
	}
}

func TestCronListWithoutLogging(t *testing.T) {
	now := time.Now().UTC()
	journal := fmt.Sprintf("%d.0 nc1 CRON[900]: (root) CMD (/usr/local/bin/galera-check.sh >/dev/null 2>&1)\n"+
		"%d.0 nc1 CRON[901]: (root) CMD (cd / && run-parts --report /etc/cron.hourly)\n", now.Add(-time.Minute).Unix(), now.Add(-time.Minute).Unix())
	c := cronHost(t, now, &journal)
	writeTree(t, c.Root, map[string]string{"/proc/812/cmdline": "/usr/sbin/cron\x00-f\x00-P\x00"}, 0o644)
	a := &Agent{Collector: c}
	res := a.cronList(context.Background())
	if res.Logging {
		t.Fatal("cron zonder -L logt geen exitcode")
	}
	for _, e := range res.Entries {
		if e.File == "/etc/cron.d/galera-bootstrap" && (e.LastResult != protocol.CronStarted || e.LastExit != nil) {
			t.Errorf("zonder -L: %+v", e)
		}
		if e.File == "/etc/crontab" && e.LastResult != protocol.CronStarted {
			t.Errorf("crontab: %+v", e)
		}
	}
}
