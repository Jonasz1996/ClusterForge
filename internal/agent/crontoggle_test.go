package agent

import (
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"github.com/Jonasz1996/clusterforge/pkg/protocol"
)

// TestCronToggle zet een gevonden regel uit en weer aan: de regel komt in
// commentaar met het merkteken, CronList meldt hem als uit, en de rest van
// het bestand blijft zoals het was.
func TestCronToggle(t *testing.T) {
	journal := ""
	c := cronHost(t, time.Now(), &journal)
	a := &Agent{Collector: c}
	find := func(file string) protocol.CronEntry {
		t.Helper()
		for _, e := range a.cronList(context.Background()).Entries {
			if e.File == file && !strings.HasPrefix(e.Schedule, "@") {
				return e
			}
		}
		t.Fatalf("%s staat er niet", file)
		return protocol.CronEntry{}
	}
	dumpFile := "/var/spool/cron/crontabs/root"
	dump := find(dumpFile)
	if !strings.Contains(dump.Command, "***") {
		t.Fatalf("commando niet gemaskeerd: %q", dump.Command)
	}
	// Er komt een regel bij boven de job: de agent vindt hem toch.
	p := filepath.Join(c.Root, dumpFile)
	data, _ := os.ReadFile(p)
	if err := os.WriteFile(p, []byte("MAILTO=jonas\n"+string(data)), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(p, 0o600); err != nil {
		t.Fatal(err)
	}
	res := a.cronToggle(&dump, false)
	if res.Error != "" || len(res.Output) != 1 || !strings.Contains(res.Output[0], "regel 4") {
		t.Fatalf("uitzetten: %+v", res)
	}
	data, _ = os.ReadFile(p)
	want := "MAILTO=jonas\n# DO NOT EDIT THIS FILE\n@reboot /usr/local/bin/start.sh\n" + protocol.CronOffPrefix +
		"15 2 * * * mysqldump -uroot -pGeheim nextcloud | gzip > /backup/nc.sql.gz\n"
	if string(data) != want {
		t.Errorf("bestand:\n%s\nwil:\n%s", data, want)
	}
	if fi, _ := os.Stat(p); fi.Mode().Perm() != 0o600 {
		t.Errorf("rechten %v", fi.Mode().Perm())
	}
	off := find(dumpFile)
	if off.Enabled || off.Schedule != dump.Schedule || off.Command != dump.Command || off.Line != 4 {
		t.Errorf("uit: %+v", off)
	}
	if res := a.cronToggle(&dump, false); res.Error != "" || !strings.Contains(res.Output[0], "stond al uit") {
		t.Errorf("nog eens uitzetten: %+v", res)
	}
	if res := a.cronToggle(&off, true); res.Error != "" {
		t.Fatalf("aanzetten: %+v", res)
	}
	data, _ = os.ReadFile(p)
	if !strings.Contains(string(data), "\n15 2 * * * mysqldump") || strings.Contains(string(data), "ClusterForge") {
		t.Errorf("weer aan:\n%s", data)
	}
	if !find(dumpFile).Enabled {
		t.Error("staat niet aan")
	}

	// Een regel met een gebruikersveld in /etc/cron.d.
	galera := find("/etc/cron.d/galera-bootstrap")
	if res := a.cronToggle(&galera, false); res.Error != "" {
		t.Fatalf("galera: %+v", res)
	}
	data, _ = os.ReadFile(filepath.Join(c.Root, "/etc/cron.d/galera-bootstrap"))
	if string(data) != "# oude cron van Jonas\n"+protocol.CronOffPrefix+"*/5 * * * * root /usr/local/bin/galera-check.sh >/dev/null 2>&1\n" {
		t.Errorf("galera:\n%s", data)
	}

	// Wat niet mag.
	for name, e := range map[string]protocol.CronEntry{
		"timer":      {Source: protocol.CronSourceTimer, File: "backup.timer"},
		"periodiek":  {Source: protocol.CronSourcePeriodic, File: "/etc/cron.daily/logrotate"},
		"ander pad":  {Source: protocol.CronSourceCronD, File: "/etc/cron.d/../passwd"},
		"andere map": {Source: protocol.CronSourceCronD, File: "/etc/ssh/sshd_config"},
		"punt":       {Source: protocol.CronSourceCronD, File: "/etc/cron.d/oud.dpkg-old"},
		"gebruiker":  {Source: protocol.CronSourceUser, File: "/var/spool/cron/crontabs/root", User: "jonas"},
		"weg":        {Source: protocol.CronSourceCronD, File: "/etc/cron.d/nextcloud-sync", User: "root", Schedule: "1 * * * *", Command: "iets anders"},
	} {
		if res := a.cronToggle(&e, false); res.Error == "" {
			t.Errorf("%s: geen fout: %+v", name, res)
		}
	}
}
